#!/usr/bin/env python3
"""tools/gen_tables.py -- build/mdbp_tables.h, generated inside the
pipeline and never by hand.

The end goal is a library, and the extraction must be a script that takes a
MariaDB source tree at any revision and produces the parser (PLAN.md S2.3):
*a parser whose tables were hand-written once cannot be regenerated for
MariaDB 14; a parser whose tables are generated by a script can.*  So the
token-name -> token-number table is derived from the artefacts bison just
wrote, and a wrong table -- the failure that would poison every number in P2,
P3 and P4 invisibly -- is caught here, before anything compiles.

Sources, in the order the phase pins them:

* ``build/parser.h``   the ``enum yytokentype`` -- the token number of every
  NAMED terminal, straight from bison's own output.
* ``build/grammar.xml``  the complete terminal list with bison's symbol
  numbers.  This is the one gap a generator over ``parser.h`` alone cannot
  close: the 22 CHARACTER-LITERAL terminals (``'('``, ``','``, ``'@'`` ...)
  are not in that enum.  Their token number is bison's own rule -- the
  character's code -- and it is computed here and cross-checked against the
  XML's ``token-number`` attribute, so neither source is trusted alone.
* ``build/rule-map.json``  serial (sql_yacc.yy file order) -> bison rule
  number.  Serial != rule number; the actions call ``MDBP_R(<serial>)`` and
  the derivation has to carry rule numbers.

The assembled terminal table is then required to reproduce
``corpus/grammar-model.json``'s terminal list EXACTLY -- same names, same
token numbers, same symbol numbers.  Any difference, or any hole in the
serial table, and this exits 3 printing the first ten, having written
nothing.

Output is deterministic (sorted by name for the lookup table, index order for
the others), because ``make regen-check`` re-runs the whole pipeline.

Exit codes: 0 ok - 2 usage or a missing input - 3 the tables disagree with
corpus/grammar-model.json (or with each other).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

EXIT_OK, EXIT_INTERNAL, EXIT_USAGE, EXIT_UNSUPPORTED = 0, 1, 2, 3

MAX_REPORTED = 10

#: `NAME = 1234,` inside parser.h's `enum yytokentype`.
ENUM_MEMBER_RE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(-?\d+)\s*,?\s*(?:/\*.*)?$")

#: bison's own names for the three pseudo-terminals, and the token numbers it
#: pins for them (`$end` is 0 and `error` is 256; `$undefined` is 257 and is
#: not part of the model's 800).
PSEUDO_TOKEN_NUMBERS = {"$end": 0, "error": 256, "$undefined": 257}


class Unsupported(Exception):
    """An input this script will not guess about."""


def _eprint(*args) -> None:
    print(*args, file=sys.stderr)


def read_parser_h_enum(path: Path) -> dict[str, int]:
    """`enum yytokentype` from parser.h -> {name: token_number}."""
    text = path.read_text()
    start = text.find("enum yytokentype")
    if start < 0:
        raise Unsupported(f"{path}: no `enum yytokentype` found")
    end = text.find("};", start)
    if end < 0:
        raise Unsupported(f"{path}: `enum yytokentype` is not closed")
    numbers: dict[str, int] = {}
    for line in text[start:end].splitlines():
        match = ENUM_MEMBER_RE.match(line)
        if match:
            numbers[match.group(1)] = int(match.group(2))
    if not numbers:
        raise Unsupported(f"{path}: `enum yytokentype` has no members")
    return numbers


def read_grammar_xml_terminals(path: Path) -> list[dict]:
    """`<terminal symbol-number= token-number= ...>` from bison's XML, in
    symbol-number order.  Same reader shape as the vendored model.py's."""
    terminals = []
    for _event, el in ET.iterparse(str(path), events=("end",)):
        tag = el.tag.rsplit("}", 1)[-1]
        if tag == "terminal":
            terminals.append(
                {
                    "name": el.get("name") or "",
                    "symbol_number": int(el.get("symbol-number") or 0),
                    "token_number": int(el.get("token-number") or 0),
                }
            )
            el.clear()
        elif tag == "terminals":
            break
    if not terminals:
        raise Unsupported(f"{path}: no <terminal> elements")
    return sorted(terminals, key=lambda t: t["symbol_number"])


def char_literal_token_number(name: str) -> int | None:
    """bison's rule: a character literal's token number is the character's
    code.  `'@'` -> 64.  Returns None when `name` is not a character
    literal."""
    if len(name) >= 3 and name[0] == "'" and name[-1] == "'":
        body = name[1:-1]
        if len(body) == 1:
            return ord(body)
        if len(body) == 2 and body[0] == "\\":
            return {"n": 10, "t": 9, "r": 13, "\\": 92, "'": 39, "0": 0}.get(body[1])
    return None


def resolve_token_numbers(
    terminals: list[dict], enum_numbers: dict[str, int]
) -> tuple[list[dict], list[str]]:
    """Give every terminal in `terminals` a token number from parser.h (named
    tokens) or from bison's character-literal rule, and cross-check it against
    the number bison wrote in the XML.  Returns (entries, differences)."""
    entries = []
    differences: list[str] = []
    for terminal in terminals:
        name = terminal["name"]
        literal = char_literal_token_number(name)
        if name in PSEUDO_TOKEN_NUMBERS:
            number = PSEUDO_TOKEN_NUMBERS[name]
            source = "bison pseudo-terminal"
        elif literal is not None:
            number = literal
            source = "character-literal rule"
        elif name in enum_numbers:
            number = enum_numbers[name]
            source = "parser.h enum yytokentype"
        else:
            differences.append(
                f"{name}: not in parser.h's enum yytokentype and not a "
                f"character literal"
            )
            continue
        if number != terminal["token_number"]:
            differences.append(
                f"{name}: {source} says token number {number}, "
                f"build/grammar.xml says {terminal['token_number']}"
            )
            continue
        entries.append(
            {
                "name": name,
                "token_number": number,
                "symbol_number": terminal["symbol_number"],
            }
        )
    return entries, differences


def compare_with_model(entries: list[dict], model: dict) -> list[str]:
    """The assembled table against corpus/grammar-model.json: same names, same
    token numbers, same symbol numbers.  Returns every difference, caller
    prints the first ten."""
    differences: list[str] = []
    theirs = {t["name"]: t for t in model.get("terminals", [])}
    ours = {e["name"]: e for e in entries}

    if len(entries) != len(ours):
        differences.append(f"the assembled table has duplicate names ({len(entries)} entries, {len(ours)} names)")
    for name in sorted(set(ours) - set(theirs)):
        differences.append(f"{name}: in the assembled table, not in the model")
    for name in sorted(set(theirs) - set(ours)):
        differences.append(f"{name}: in the model, not in the assembled table")
    for name in sorted(set(ours) & set(theirs)):
        if ours[name]["token_number"] != theirs[name]["token_number"]:
            differences.append(
                f"{name}: token number {ours[name]['token_number']} here, "
                f"{theirs[name]['token_number']} in the model"
            )
        elif ours[name]["symbol_number"] != theirs[name]["symbol_number"]:
            differences.append(
                f"{name}: symbol number {ours[name]['symbol_number']} here, "
                f"{theirs[name]['symbol_number']} in the model"
            )
    return differences


def serial_table(rule_map: dict) -> tuple[list[int], list[str]]:
    """rule-map.json's serial_to_rule -> a dense array over serials 0..N-1.
    A hole is a difference, not a default."""
    serial_to_rule = rule_map.get("serial_to_rule")
    if not isinstance(serial_to_rule, dict) or not serial_to_rule:
        return [], ["build/rule-map.json: serial_to_rule is missing or empty"]
    serials = sorted(int(s) for s in serial_to_rule)
    differences: list[str] = []
    expected = list(range(len(serials)))
    if serials != expected:
        missing = sorted(set(expected) - set(serials))
        for serial in missing[:MAX_REPORTED]:
            differences.append(f"serial {serial} is missing from rule-map.json")
        for serial in sorted(set(serials) - set(expected))[:MAX_REPORTED]:
            differences.append(f"serial {serial} is outside 0..{len(serials) - 1}")
        if not differences:
            differences.append("rule-map.json's serials are not 0..N-1")
        return [], differences
    return [int(serial_to_rule[str(s)]) for s in serials], []


def c_string(value: str) -> str:
    out = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{out}"'


def render_header(entries: list[dict], serials: list[int]) -> str:
    by_name = sorted(entries, key=lambda e: e["name"])
    kinds = max(e["symbol_number"] for e in entries) + 1
    names_by_kind: list[str | None] = [None] * kinds
    for entry in entries:
        names_by_kind[entry["symbol_number"]] = entry["name"]

    # PLAN.md P2.1 (D-5): every name is stored INLINE, as a fixed-size char
    # array, rather than as a `const char *` into a string literal elsewhere
    # in the object.  A `const char *` member still needs a load-time
    # relocation to fix up for the library's actual load address (ASLR), so
    # the table lands in .data.rel.ro -- writable until the loader's RELRO
    # pass, not .rodata -- even though every byte in it is compile-time
    # constant.  A fixed-size array has no pointer to relocate: the bytes
    # ARE the data, so the whole table can be truly const, in .rodata, for
    # the life of the process.  Width is derived from the actual names, with
    # one more byte for the NUL, never hand-picked: a hand-picked width is
    # exactly the kind of silent-truncation bug this generator exists to
    # rule out (see the module docstring).
    # mdbp_symbol_name() (src/mdbp_runtime.c) reads an empty stored name as
    # "no name for this kind" (bison's $undefined hole, see the comment
    # below) -- a model entry that carried an empty name for a REAL
    # terminal would silently render that terminal unnamed instead of
    # failing loudly, so the premise is checked here rather than merely
    # asserted in the comment.
    empty_named = [e["token_number"] for e in entries if not e["name"]]
    assert not empty_named, (
        f"terminal(s) with an empty name in the model: token_number(s) "
        f"{empty_named} -- mdbp_symbol_name()'s empty-string hole must stay "
        "reserved for bison's $undefined, never a real terminal"
    )
    name_width = max(len(e["name"]) for e in entries) + 1

    lines = [
        "/* build/mdbp_tables.h -- GENERATED by tools/gen_tables.py inside",
        " * tools/extract.sh.  Never edit this file, and never hand-write a",
        " * token table: that is how you get a silent off-by-one against 800",
        " * terminals that still compiles and still parses most inputs.",
        " *",
        " * Sources: build/parser.h (enum yytokentype), build/grammar.xml (the",
        " * terminal list and bison's symbol numbers; character-literal token",
        " * numbers are the character's own code) and build/rule-map.json.",
        " * Checked against corpus/grammar-model.json before being written.",
        " *",
        " * Terminal names are fixed-size char arrays, not `const char *`, so",
        " * that mdbp_terminals and mdbp_symbol_names below need no load-time",
        " * relocation and land in .rodata (PLAN.md P2.1, D-5).",
        " */",
        "#ifndef MDBP_TABLES_H",
        "#define MDBP_TABLES_H",
        "",
        f"#define MDBP_TERMINAL_COUNT {len(by_name)}",
        f"#define MDBP_SERIAL_COUNT {len(serials)}",
        f"#define MDBP_SYMBOL_KIND_COUNT {kinds}",
        f"#define MDBP_TERMINAL_NAME_MAX {name_width}",
        "",
        "typedef struct mdbp_terminal {",
        "    char name[MDBP_TERMINAL_NAME_MAX];",
        "    int token_number;",
        "    int symbol_kind;",
        "} mdbp_terminal;",
        "",
        "/* Sorted by strcmp order, so a lookup is a bsearch. */",
        "static const mdbp_terminal mdbp_terminals[MDBP_TERMINAL_COUNT] = {",
    ]
    for entry in by_name:
        lines.append(
            f"    {{ {c_string(entry['name'])}, {entry['token_number']}, "
            f"{entry['symbol_number']} }},"
        )
    lines += [
        "};",
        "",
        "/* Bison symbol kind -> terminal name, for error.expected_sample.  The",
        " * hole is bison's own $undefined, which the model does not carry:",
        " * an empty string marks it (no terminal name is ever empty), so the",
        " * hole needs no null pointer and therefore no relocation either. */",
        "static const char mdbp_symbol_names[MDBP_SYMBOL_KIND_COUNT][MDBP_TERMINAL_NAME_MAX] = {",
    ]
    for kind, name in enumerate(names_by_kind):
        rendered = c_string(name) if name is not None else c_string("")
        lines.append(f"    {rendered},  /* {kind} */")
    lines += [
        "};",
        "",
        "/* Serial (sql_yacc.yy file order) -> bison rule number. */",
        "static const int mdbp_serial_to_rule[MDBP_SERIAL_COUNT] = {",
    ]
    for start in range(0, len(serials), 12):
        chunk = ", ".join(str(rule) for rule in serials[start:start + 12])
        lines.append(f"    {chunk},")
    lines += [
        "};",
        "",
        "#endif /* MDBP_TABLES_H */",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="gen_tables.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument("--parser-h", default=str(common.BUILD_DIR / "parser.h"))
    ap.add_argument("--grammar-xml", default=str(common.BUILD_DIR / "grammar.xml"))
    ap.add_argument("--rule-map", default=str(common.BUILD_DIR / "rule-map.json"))
    ap.add_argument(
        "--model", default=str(common.corpus_path("corpus/grammar-model.json"))
    )
    ap.add_argument("--out", default=str(common.BUILD_DIR / "mdbp_tables.h"))
    args = ap.parse_args(argv)

    paths = {
        "--parser-h": Path(args.parser_h),
        "--grammar-xml": Path(args.grammar_xml),
        "--rule-map": Path(args.rule_map),
        "--model": Path(args.model),
    }
    for flag, path in paths.items():
        if not path.is_file():
            _eprint(f"gen_tables.py: {flag} {path}: no such file")
            return EXIT_USAGE

    try:
        enum_numbers = read_parser_h_enum(paths["--parser-h"])
        terminals = read_grammar_xml_terminals(paths["--grammar-xml"])
    except Unsupported as exc:
        _eprint(f"gen_tables.py: {exc}")
        return EXIT_UNSUPPORTED
    except ET.ParseError as exc:
        _eprint(f"gen_tables.py: {paths['--grammar-xml']}: {exc}")
        return EXIT_UNSUPPORTED

    entries, differences = resolve_token_numbers(terminals, enum_numbers)

    try:
        model = json.loads(paths["--model"].read_text())
        rule_map = json.loads(paths["--rule-map"].read_text())
    except json.JSONDecodeError as exc:
        _eprint(f"gen_tables.py: {exc}")
        return EXIT_UNSUPPORTED

    differences += compare_with_model(entries, model)
    serials, serial_differences = serial_table(rule_map)
    differences += serial_differences

    if differences:
        # Name every source that can produce a difference, not just the
        # model: resolve_token_numbers() reports parser.h disagreeing with
        # build/grammar.xml, and serial_table() reports holes in
        # rule-map.json.  Naming the model alone sends the reader to a file
        # that had no part in those failures.
        _eprint(
            f"gen_tables.py: the generated tables do not agree with their "
            f"sources ({paths['--parser-h']}, {paths['--grammar-xml']}, "
            f"{paths['--model']}, {paths['--rule-map']}) "
            f"({len(differences)} differences; "
            f"first {min(MAX_REPORTED, len(differences))}):"
        )
        for line in differences[:MAX_REPORTED]:
            _eprint(f"  {line}")
        _eprint("gen_tables.py: nothing was written")
        return EXIT_UNSUPPORTED

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_header(entries, serials))

    print(
        json.dumps(
            {
                "out": common.display_path(out),
                "terminals": len(entries),
                "serials": len(serials),
                "symbol_kinds": max(e["symbol_number"] for e in entries) + 1,
            },
            sort_keys=True,
        )
    )
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
